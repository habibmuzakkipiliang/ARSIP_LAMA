import re

def jalankan_kodein(kode_sumber):
    # Kamus Terjemahan
    kamus = {
        'spill': 'print',
        'tanya': 'input',
        'kalo': 'if',
        'ataugak': 'elif',
        'selainitu': 'else',
        'ulang': 'for',
        'selama': 'while',
        'tugas': 'def',
        'kasih': 'return',
        'bener': 'True',
        'salah': 'False',
        'panggil': 'import',
        'coba': 'try',
        'kaloerror': 'except',
        'cabut': 'break',
        'lanjut': 'continue'
    }

    # Proses replace kata kunci
    kode_python = kode_sumber
    for indo, py in kamus.items():
        # Menggunakan regex agar tidak mengganti kata di dalam string
        kode_python = re.sub(rf'\b{indo}\b', py, kode_python)

    # Eksekusi kode hasil terjemahan
    exec(kode_python)

