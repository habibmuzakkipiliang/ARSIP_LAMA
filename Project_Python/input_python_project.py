# input dan arimatika dasar

a = int (input ("Angka 1 : "))
b = int (input ("Angka 2 : "))
c = int (input ("Angka 3 : "))

print ("Hasil penjumlahan : ", a + b + c)
print ("Hasil pengurangan : ", a - b - c)
print ("Hasil perkalian : ", a * b * c)
print ("Hasil pembagian : ", a / b / c)
print ("Hasil modulus : ", a % b % c)
print ("Hasil floor division : ", a // b // c)