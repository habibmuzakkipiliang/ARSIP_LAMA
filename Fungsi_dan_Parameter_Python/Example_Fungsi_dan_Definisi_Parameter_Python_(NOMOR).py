# latihan 4
def aztec (r,y):
    return r + y
hasil = aztec (100,100)
print (f"Hasilnya adalah {aztec}")

def hujan (h,p):
    return h * p
hasil = hujan (7000,7000)
print (f"Hasilnya adalah {hujan}")

def minang (i,o):
    return i ** o
hasil = minang (9000,9000)
print (f"Hasilnya adalah {minang}")

def unit (o,p):
    return o % p
hasil = unit (9,2)
print (f"Hasilnya adalah {unit}")